-- 나. 참가기관 의견 회신 취합. 결제원 담당자가 의견 요청을 만들고 대상 기관이 회신한다.
-- 의견 요청. 상태는 작성중(DRAFT) → 회신중(OPEN) → 마감(CLOSED). 회신중에 취소하면 마감으로 가고 cancelled 가 참이다.
-- 작성한 결제원 담당자는 그때의 이메일과 이름으로 남긴다(수정 요청 알림을 받는 사람).
CREATE TABLE opinion_request (
    id             BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business       VARCHAR(30)    NOT NULL,
    title          VARCHAR(200)   NOT NULL,
    content        VARCHAR(4000)  NOT NULL,
    due_date       DATE           NOT NULL,
    status         VARCHAR(20)    NOT NULL,
    owner_email    VARCHAR(200)   NOT NULL,
    owner_name     VARCHAR(50)    NOT NULL,
    opened_at      TIMESTAMP,
    closed_at      TIMESTAMP,
    cancelled      BOOLEAN        NOT NULL DEFAULT FALSE,
    cancel_reason  VARCHAR(500),
    created_at     TIMESTAMP      NOT NULL,
    created_by     VARCHAR(100)   NOT NULL,
    updated_at     TIMESTAMP      NOT NULL,
    updated_by     VARCHAR(100)   NOT NULL,
    CONSTRAINT ck_opinion_request_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS')),
    CONSTRAINT ck_opinion_request_status CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED'))
);

CREATE INDEX ix_opinion_request_business ON opinion_request (business, status, due_date);

-- 업권별 회신 양식. 요청마다 이름(예: 은행권)을 정하고 양식 파일은 첨부(OPINION_REPLY_FORM)로 붙인다. 대상 기관마다 양식을 하나 고른다.
CREATE TABLE opinion_reply_form (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   BIGINT        NOT NULL,
    name         VARCHAR(50)   NOT NULL,
    description  VARCHAR(500),
    sort_order   INT           NOT NULL,
    created_at   TIMESTAMP     NOT NULL,
    created_by   VARCHAR(100)  NOT NULL,
    updated_at   TIMESTAMP     NOT NULL,
    updated_by   VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_opinion_reply_form_request FOREIGN KEY (request_id) REFERENCES opinion_request (id),
    CONSTRAINT uk_opinion_reply_form_name UNIQUE (request_id, name)
);

-- 의견 요청의 대상 기관 한 곳.
CREATE TABLE opinion_target (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       BIGINT        NOT NULL,
    organization_id  BIGINT        NOT NULL,
    form_id          BIGINT,
    created_at       TIMESTAMP     NOT NULL,
    created_by       VARCHAR(100)  NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    updated_by       VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_opinion_target_request FOREIGN KEY (request_id) REFERENCES opinion_request (id),
    CONSTRAINT fk_opinion_target_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_opinion_target_form FOREIGN KEY (form_id) REFERENCES opinion_reply_form (id),
    CONSTRAINT uk_opinion_target UNIQUE (request_id, organization_id)
);

-- 대상 기관의 회신 담당자. 결제원 담당자가 기관 담당자(계정) 중에서 고르고 의견 요청 메일을 받는다.
-- 고를 때의 이메일·이름·세부업무를 남긴다. 계정이 탈퇴하면 이 행을 지운다.
CREATE TABLE opinion_target_recipient (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_id     BIGINT        NOT NULL,
    account_id    BIGINT        NOT NULL,
    email         VARCHAR(200)  NOT NULL,
    name          VARCHAR(50)   NOT NULL,
    sub_business  VARCHAR(200),
    created_at    TIMESTAMP     NOT NULL,
    created_by    VARCHAR(100)  NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    updated_by    VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_opinion_target_recipient_target FOREIGN KEY (target_id) REFERENCES opinion_target (id),
    CONSTRAINT uk_opinion_target_recipient UNIQUE (target_id, account_id)
);

-- 기관 회신. 대상 기관 한 곳에 하나다. reply_type·content 는 제출한 내용이고 draft_* 는 임시저장한 내용이다.
-- 상태는 임시저장(DRAFT) → 제출(SUBMITTED) → 수정 요청(REVISION_REQUESTED) → 수정 중(REVISING, 결제원 승인) → 다시 제출.
CREATE TABLE opinion_reply (
    id                         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_id                  BIGINT         NOT NULL,
    status                     VARCHAR(30)    NOT NULL,
    reply_type                 VARCHAR(20),
    content                    VARCHAR(4000),
    draft_type                 VARCHAR(20),
    draft_content              VARCHAR(4000),
    replier_email              VARCHAR(200),
    replier_name               VARCHAR(50),
    submitted_at               TIMESTAMP,
    revision_reason            VARCHAR(500),
    revision_requested_at      TIMESTAMP,
    revision_rejection_reason  VARCHAR(500),
    created_at                 TIMESTAMP      NOT NULL,
    created_by                 VARCHAR(100)   NOT NULL,
    updated_at                 TIMESTAMP      NOT NULL,
    updated_by                 VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_opinion_reply_target FOREIGN KEY (target_id) REFERENCES opinion_target (id),
    CONSTRAINT uk_opinion_reply_target UNIQUE (target_id),
    CONSTRAINT ck_opinion_reply_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'REVISION_REQUESTED', 'REVISING')),
    CONSTRAINT ck_opinion_reply_type CHECK (reply_type IN ('AGREE', 'CONDITIONAL', 'DISAGREE')),
    CONSTRAINT ck_opinion_reply_draft_type CHECK (draft_type IN ('AGREE', 'CONDITIONAL', 'DISAGREE'))
);

-- 미회신 기관에 보낸 리마인드 메일 한 번. 보낸 사람과 그때 받은 기관 이름들을 남긴다.
CREATE TABLE opinion_reminder (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id          BIGINT         NOT NULL,
    sender_name         VARCHAR(50)    NOT NULL,
    organization_count  INT            NOT NULL,
    recipient_count     INT            NOT NULL,
    organization_names  VARCHAR(2000)  NOT NULL,
    created_at          TIMESTAMP      NOT NULL,
    created_by          VARCHAR(100)   NOT NULL,
    updated_at          TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_opinion_reminder_request FOREIGN KEY (request_id) REFERENCES opinion_request (id)
);

CREATE INDEX ix_opinion_reminder_request ON opinion_reminder (request_id, created_at);
