-- 기관의 업무 참여. 기관 하나가 여러 업무 영역(계좌통합관리, 자동이체통합관리, 대출이동, CMS)에 참여한다.
-- 레일(업무 영역)별 조회 범위의 기준이 된다.
CREATE TABLE organization_business (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  BIGINT        NOT NULL,
    business         VARCHAR(30)   NOT NULL,
    created_at       TIMESTAMP     NOT NULL,
    created_by       VARCHAR(100)  NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    updated_by       VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_organization_business_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT uk_organization_business UNIQUE (organization_id, business),
    CONSTRAINT ck_organization_business_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS'))
);
