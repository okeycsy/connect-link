-- 가입 때 회사 이메일 인증. 코드를 보낼 때마다 한 줄이 생기고, 확인은 그 이메일의 가장 최근 줄로 한다.
-- 코드와 인증 토큰은 원문을 남기지 않고 해시만 둔다.
CREATE TABLE email_verification (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(200)  NOT NULL,
    code_hash         VARCHAR(100)  NOT NULL,
    issued_at         TIMESTAMP     NOT NULL,
    expires_at        TIMESTAMP     NOT NULL,
    failed_attempts   INTEGER       NOT NULL DEFAULT 0,
    verified_at       TIMESTAMP,
    token_hash        VARCHAR(64),
    token_expires_at  TIMESTAMP,
    consumed_at       TIMESTAMP,
    created_at        TIMESTAMP     NOT NULL,
    created_by        VARCHAR(100)  NOT NULL,
    updated_at        TIMESTAMP     NOT NULL,
    updated_by        VARCHAR(100)  NOT NULL,
    CONSTRAINT uk_email_verification_token UNIQUE (token_hash)
);

CREATE INDEX ix_email_verification_email ON email_verification (email);
