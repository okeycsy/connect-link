-- 기관 테스트 담당자. 대상 기관 한 곳에서 결제원 담당자가 담당자 연락처(그 기관·같은 업무) 중에서 세부업무를 보고 고른 사람이다.
-- 테스트 열림·테스트데이터 요청·기한 리마인드 메일을 받는다. 아무도 고르지 않은 기관은 그 기관의 업무 담당자(사용 중 계정) 전원이 받는다.
-- 고를 때의 이메일·이름·세부업무를 남기고, 계정과는 회사 이메일로만 잇는다.
CREATE TABLE test_plan_target_contact (
    id                   BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_plan_target_id  BIGINT         NOT NULL,
    email                VARCHAR(200)   NOT NULL,
    name                 VARCHAR(50)    NOT NULL,
    sub_business         VARCHAR(200),
    created_at           TIMESTAMP      NOT NULL,
    created_by           VARCHAR(100)   NOT NULL,
    updated_at           TIMESTAMP      NOT NULL,
    updated_by           VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_test_plan_target_contact_target FOREIGN KEY (test_plan_target_id) REFERENCES test_plan_target (id),
    CONSTRAINT uk_test_plan_target_contact UNIQUE (test_plan_target_id, email)
);
