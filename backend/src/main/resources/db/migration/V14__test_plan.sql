-- 다. 기관 테스트 수행·결과 관리. 결제원 담당자가 단위업무/개발 건마다 테스트 페이지를 만들고, 대상 참가기관 담당자가 요구사항별 결과를 등록한다.
-- 요구사항 하나가 완료되려면 기관 결과가 정상(PASSED)이고 결제원 미니 수행률이 100 이어야 한다. 모든 대상 기관의 모든 요구사항이 완료면 테스트 수행 완료(completed_at)다.
-- 수행률(progress_rate, 0~100)은 결과가 바뀔 때마다 서버가 다시 계산해 둔다. 목록과 홈 카드가 결과 행을 다 읽지 않게 하려는 것이다.
CREATE TABLE test_plan (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business        VARCHAR(30)    NOT NULL,
    sub_business    VARCHAR(200)   NOT NULL,
    title           VARCHAR(200)   NOT NULL,
    description     VARCHAR(4000),
    start_date      DATE           NOT NULL,
    end_date        DATE           NOT NULL,
    owner_email     VARCHAR(200)   NOT NULL,
    owner_name      VARCHAR(50)    NOT NULL,
    progress_rate   INT            NOT NULL,
    completed_at    TIMESTAMP,
    created_at      TIMESTAMP      NOT NULL,
    created_by      VARCHAR(100)   NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    updated_by      VARCHAR(100)   NOT NULL,
    CONSTRAINT ck_test_plan_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS')),
    CONSTRAINT ck_test_plan_period CHECK (end_date >= start_date),
    CONSTRAINT ck_test_plan_progress_rate CHECK (progress_rate BETWEEN 0 AND 100)
);

CREATE INDEX ix_test_plan_business ON test_plan (business, completed_at);

-- 테스트 요구사항. 번호(001, 002 …)는 sort_order 순서로 화면이 붙인다.
CREATE TABLE test_item (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_plan_id    BIGINT         NOT NULL,
    sort_order      INT            NOT NULL,
    title           VARCHAR(500)   NOT NULL,
    description     VARCHAR(2000),
    created_at      TIMESTAMP      NOT NULL,
    created_by      VARCHAR(100)   NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    updated_by      VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_test_item_plan FOREIGN KEY (test_plan_id) REFERENCES test_plan (id)
);

CREATE INDEX ix_test_item_plan ON test_item (test_plan_id, sort_order);

-- 테스트 대상 참가기관 한 곳. 그 기관의 수행률·완료 요구사항 수·마지막 결과 등록 일시를 함께 둔다.
CREATE TABLE test_plan_target (
    id                BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_plan_id      BIGINT         NOT NULL,
    organization_id   BIGINT         NOT NULL,
    progress_rate     INT            NOT NULL,
    completed_count   INT            NOT NULL,
    last_reported_at  TIMESTAMP,
    created_at        TIMESTAMP      NOT NULL,
    created_by        VARCHAR(100)   NOT NULL,
    updated_at        TIMESTAMP      NOT NULL,
    updated_by        VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_test_plan_target_plan FOREIGN KEY (test_plan_id) REFERENCES test_plan (id),
    CONSTRAINT fk_test_plan_target_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT uk_test_plan_target UNIQUE (test_plan_id, organization_id),
    CONSTRAINT ck_test_plan_target_progress_rate CHECK (progress_rate BETWEEN 0 AND 100)
);

CREATE INDEX ix_test_plan_target_organization ON test_plan_target (organization_id);

-- 대상 기관 하나가 요구사항 하나에 등록한 결과와 그에 대한 결제원 의견(미니 수행률·특이사항).
-- 결과: 정상(PASSED), 오류(FAILED), 수행중(IN_PROGRESS), 미수행(NOT_STARTED). 오류면 특이사항(오류내용)이 있다.
-- 등록·의견을 남긴 사람은 그때의 이메일·이름으로 남긴다.
CREATE TABLE test_item_result (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_item_id        BIGINT         NOT NULL,
    test_plan_target_id BIGINT         NOT NULL,
    result              VARCHAR(20)    NOT NULL,
    note                VARCHAR(2000),
    reported_by_email   VARCHAR(200)   NOT NULL,
    reported_by_name    VARCHAR(50)    NOT NULL,
    reported_at         TIMESTAMP      NOT NULL,
    feedback_rate       INT,
    feedback_note       VARCHAR(2000),
    feedback_by_email   VARCHAR(200),
    feedback_by_name    VARCHAR(50),
    feedback_at         TIMESTAMP,
    created_at          TIMESTAMP      NOT NULL,
    created_by          VARCHAR(100)   NOT NULL,
    updated_at          TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_test_item_result_item FOREIGN KEY (test_item_id) REFERENCES test_item (id),
    CONSTRAINT fk_test_item_result_target FOREIGN KEY (test_plan_target_id) REFERENCES test_plan_target (id),
    CONSTRAINT uk_test_item_result UNIQUE (test_item_id, test_plan_target_id),
    CONSTRAINT ck_test_item_result_result CHECK (result IN ('PASSED', 'FAILED', 'IN_PROGRESS', 'NOT_STARTED')),
    CONSTRAINT ck_test_item_result_feedback_rate CHECK (feedback_rate IS NULL OR feedback_rate BETWEEN 0 AND 100)
);

CREATE INDEX ix_test_item_result_target ON test_item_result (test_plan_target_id);

-- 기관이 결과를 등록하면 매터모스트 알림을 받을 결제원 담당자. 테스트마다 정하고, 만든 사람이 처음 들어간다.
CREATE TABLE test_plan_recipient (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_plan_id    BIGINT         NOT NULL,
    account_id      BIGINT,
    email           VARCHAR(200)   NOT NULL,
    name            VARCHAR(50)    NOT NULL,
    created_at      TIMESTAMP      NOT NULL,
    created_by      VARCHAR(100)   NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    updated_by      VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_test_plan_recipient_plan FOREIGN KEY (test_plan_id) REFERENCES test_plan (id),
    CONSTRAINT uk_test_plan_recipient UNIQUE (test_plan_id, email)
);
