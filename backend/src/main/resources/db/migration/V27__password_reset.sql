-- 비밀번호 찾기. 회사 이메일로 숫자 6자리 코드를 보낼 때마다 한 줄이 생기고, 확인은 그 이메일의 가장 최근 줄로 한다.
-- 코드는 원문을 남기지 않고 해시만 둔다. 새 비밀번호로 바꾸면 used_at 을 남겨 같은 코드를 다시 못 쓴다.
CREATE TABLE password_reset (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(200)  NOT NULL,
    code_hash         VARCHAR(100)  NOT NULL,
    issued_at         TIMESTAMP     NOT NULL,
    expires_at        TIMESTAMP     NOT NULL,
    failed_attempts   INTEGER       NOT NULL DEFAULT 0,
    used_at           TIMESTAMP,
    created_at        TIMESTAMP     NOT NULL,
    created_by        VARCHAR(100)  NOT NULL,
    updated_at        TIMESTAMP     NOT NULL,
    updated_by        VARCHAR(100)  NOT NULL
);

CREATE INDEX ix_password_reset_email ON password_reset (email);

-- 비밀번호를 마지막으로 바꾼 시각. 비밀번호를 바꾸기 전에 로그인한 다른 세션을 끝내는 기준이다.
ALTER TABLE user_account ADD COLUMN password_changed_at TIMESTAMP;
