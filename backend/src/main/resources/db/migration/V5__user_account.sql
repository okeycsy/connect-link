-- 계정. 로그인 주체이며 가입 때 받은 소속·직무·연락처 정보를 함께 둔다. 이메일은 소문자로 저장한다.
CREATE TABLE user_account (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            VARCHAR(200)  NOT NULL,
    password_hash    VARCHAR(100)  NOT NULL,
    name             VARCHAR(50)   NOT NULL,
    organization_id  BIGINT        NOT NULL,
    status           VARCHAR(30)   NOT NULL,
    admin            BOOLEAN       NOT NULL DEFAULT FALSE,
    job_role         VARCHAR(20)   NOT NULL,
    department       VARCHAR(100)  NOT NULL,
    team             VARCHAR(100)  NOT NULL,
    job_title        VARCHAR(50)   NOT NULL,
    extension_phone  VARCHAR(30)   NOT NULL,
    mobile_phone     VARCHAR(30),
    created_at       TIMESTAMP     NOT NULL,
    created_by       VARCHAR(100)  NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    updated_by       VARCHAR(100)  NOT NULL,
    CONSTRAINT uk_user_account_email UNIQUE (email),
    CONSTRAINT fk_user_account_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_user_account_status CHECK (status IN ('PENDING_APPROVAL', 'ACTIVE', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_user_account_job_role CHECK (job_role IN ('BUSINESS', 'IT'))
);

-- 계정의 담당 업무와 업무별 세부업무(자유 텍스트).
CREATE TABLE user_account_business (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT        NOT NULL,
    business      VARCHAR(30)   NOT NULL,
    sub_business  VARCHAR(200),
    created_at    TIMESTAMP     NOT NULL,
    created_by    VARCHAR(100)  NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    updated_by    VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_user_account_business_account FOREIGN KEY (account_id) REFERENCES user_account (id),
    CONSTRAINT uk_user_account_business UNIQUE (account_id, business),
    CONSTRAINT ck_user_account_business_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS'))
);

-- 계정의 전산 세부 직무(복수). 직무가 전산일 때만 있다.
CREATE TABLE user_account_it_role (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT        NOT NULL,
    it_role     VARCHAR(30)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL,
    created_by  VARCHAR(100)  NOT NULL,
    updated_at  TIMESTAMP     NOT NULL,
    updated_by  VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_user_account_it_role_account FOREIGN KEY (account_id) REFERENCES user_account (id),
    CONSTRAINT uk_user_account_it_role UNIQUE (account_id, it_role),
    CONSTRAINT ck_user_account_it_role CHECK (it_role IN ('DEV', 'OPS', 'INFRA', 'EXTERNAL_LINK', 'CONTROL_ROOM'))
);
