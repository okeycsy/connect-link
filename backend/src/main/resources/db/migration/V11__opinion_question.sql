-- 의견 요청: 업권별 회신 양식을 없애고 요청마다 질문(객관식·주관식)을 둔다(SHY 요청). 대상은 업권별로 고르므로 양식을 따로 묶지 않는다.
DELETE FROM attachment WHERE owner_type = 'OPINION_REPLY_FORM';
ALTER TABLE opinion_target DROP CONSTRAINT fk_opinion_target_form;
ALTER TABLE opinion_target DROP COLUMN form_id;
DROP TABLE opinion_reply_form;

-- 요청의 질문 하나. 유형은 객관식 하나 고르기(SINGLE_CHOICE), 여러 개 고르기(MULTIPLE_CHOICE), 주관식(TEXT).
-- 회신을 받기 시작하면(회신중) 질문은 고치지 않는다.
CREATE TABLE opinion_question (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id     BIGINT        NOT NULL,
    sort_order     INT           NOT NULL,
    question_type  VARCHAR(20)   NOT NULL,
    title          VARCHAR(500)  NOT NULL,
    required       BOOLEAN       NOT NULL,
    created_at     TIMESTAMP     NOT NULL,
    created_by     VARCHAR(100)  NOT NULL,
    updated_at     TIMESTAMP     NOT NULL,
    updated_by     VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_opinion_question_request FOREIGN KEY (request_id) REFERENCES opinion_request (id),
    CONSTRAINT ck_opinion_question_type CHECK (question_type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE', 'TEXT'))
);

CREATE INDEX ix_opinion_question_request ON opinion_question (request_id, sort_order);

-- 객관식 질문의 선택지.
CREATE TABLE opinion_question_option (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  BIGINT        NOT NULL,
    sort_order   INT           NOT NULL,
    label        VARCHAR(200)  NOT NULL,
    created_at   TIMESTAMP     NOT NULL,
    created_by   VARCHAR(100)  NOT NULL,
    updated_at   TIMESTAMP     NOT NULL,
    updated_by   VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_opinion_question_option_question FOREIGN KEY (question_id) REFERENCES opinion_question (id)
);

-- 기관 회신의 답 한 칸. 회신처럼 제출한 답(SUBMITTED)과 임시저장한 답(DRAFT)을 따로 둔다.
-- 주관식은 질문마다 한 행(text_value), 객관식은 고른 선택지마다 한 행(option_id)이다.
CREATE TABLE opinion_reply_answer (
    id           BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reply_id     BIGINT         NOT NULL,
    question_id  BIGINT         NOT NULL,
    stage        VARCHAR(20)    NOT NULL,
    option_id    BIGINT,
    text_value   VARCHAR(4000),
    created_at   TIMESTAMP      NOT NULL,
    created_by   VARCHAR(100)   NOT NULL,
    updated_at   TIMESTAMP      NOT NULL,
    updated_by   VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_opinion_reply_answer_reply FOREIGN KEY (reply_id) REFERENCES opinion_reply (id),
    CONSTRAINT fk_opinion_reply_answer_question FOREIGN KEY (question_id) REFERENCES opinion_question (id),
    CONSTRAINT fk_opinion_reply_answer_option FOREIGN KEY (option_id) REFERENCES opinion_question_option (id),
    CONSTRAINT ck_opinion_reply_answer_stage CHECK (stage IN ('SUBMITTED', 'DRAFT'))
);

CREATE INDEX ix_opinion_reply_answer_reply ON opinion_reply_answer (reply_id, stage);
