-- 첨부파일. 파일 내용은 FileStorage(프로토타입은 임시 디렉터리)에 있고 여기에는 메타데이터만 둔다.
-- owner_type 은 기능 모듈이 늘려 가므로 CHECK 를 두지 않는다.
CREATE TABLE attachment (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type     VARCHAR(30)   NOT NULL,
    owner_id       BIGINT        NOT NULL,
    original_name  VARCHAR(255)  NOT NULL,
    content_type   VARCHAR(100)  NOT NULL,
    size_bytes     BIGINT        NOT NULL,
    storage_key    VARCHAR(200)  NOT NULL,
    created_at     TIMESTAMP     NOT NULL,
    created_by     VARCHAR(100)  NOT NULL,
    updated_at     TIMESTAMP     NOT NULL,
    updated_by     VARCHAR(100)  NOT NULL,
    CONSTRAINT uk_attachment_storage_key UNIQUE (storage_key)
);

CREATE INDEX ix_attachment_owner ON attachment (owner_type, owner_id);

-- 변경 이력. 대상 한 건의 변경 전·후 값을 JSON 배열(changes)로 남긴다. 한 번 쓰면 고치지 않는다.
-- created_at, created_by 가 변경 일시·변경자다. target_type 도 기능 모듈이 늘려 가므로 CHECK 를 두지 않는다.
CREATE TABLE change_history (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type  VARCHAR(30)   NOT NULL,
    target_id    BIGINT        NOT NULL,
    business     VARCHAR(30),
    action       VARCHAR(20)   NOT NULL,
    summary      VARCHAR(200)  NOT NULL,
    actor_name   VARCHAR(100)  NOT NULL,
    changes      CLOB          NOT NULL,
    created_at   TIMESTAMP     NOT NULL,
    created_by   VARCHAR(100)  NOT NULL,
    updated_at   TIMESTAMP     NOT NULL,
    updated_by   VARCHAR(100)  NOT NULL,
    CONSTRAINT ck_change_history_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS')),
    CONSTRAINT ck_change_history_action CHECK (action IN ('CREATED', 'UPDATED', 'DELETED'))
);

CREATE INDEX ix_change_history_target ON change_history (target_type, target_id, created_at);
