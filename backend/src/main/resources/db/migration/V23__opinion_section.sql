-- 의견 요청 섹션과 답변에 따른 섹션 이동(SHY 요청, 구글폼의 섹션·"답변을 기준으로 섹션 이동"과 같다).
-- 질문은 섹션에 묶인다. 섹션마다 "이 섹션 다음" 이동을, 객관식(하나 고르기) 선택지마다 "이 답을 고르면" 이동을 정한다.
-- 이동(jump_type): SECTION(jump_order 번째 섹션으로, 0부터, 지금 섹션보다 뒤만), END(회신 끝내기). 비어 있으면 바로 다음 섹션이다.
-- 기관은 자기 답으로 정해진 경로의 섹션만 답한다.
CREATE TABLE opinion_section (
    id           BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   BIGINT         NOT NULL,
    sort_order   INT            NOT NULL,
    title        VARCHAR(200),
    description  VARCHAR(2000),
    jump_type    VARCHAR(10),
    jump_order   INT,
    created_at   TIMESTAMP      NOT NULL,
    created_by   VARCHAR(100)   NOT NULL,
    updated_at   TIMESTAMP      NOT NULL,
    updated_by   VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_opinion_section_request FOREIGN KEY (request_id) REFERENCES opinion_request (id),
    CONSTRAINT ck_opinion_section_jump CHECK (jump_type IN ('SECTION', 'END'))
);

CREATE INDEX ix_opinion_section_request ON opinion_section (request_id, sort_order);

-- 지금까지의 요청은 제목 없는 섹션 하나에 질문을 모두 담는다.
INSERT INTO opinion_section (request_id, sort_order, created_at, created_by, updated_at, updated_by)
SELECT id, 0, created_at, created_by, updated_at, updated_by FROM opinion_request;

ALTER TABLE opinion_question ADD COLUMN section_id BIGINT;
UPDATE opinion_question SET section_id = (SELECT s.id FROM opinion_section s WHERE s.request_id = opinion_question.request_id);
ALTER TABLE opinion_question ADD CONSTRAINT fk_opinion_question_section FOREIGN KEY (section_id) REFERENCES opinion_section (id);

ALTER TABLE opinion_question_option ADD COLUMN jump_type VARCHAR(10);
ALTER TABLE opinion_question_option ADD COLUMN jump_order INT;
ALTER TABLE opinion_question_option ADD CONSTRAINT ck_opinion_question_option_jump CHECK (jump_type IN ('SECTION', 'END'));
