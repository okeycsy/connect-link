-- 정기 변경(현행화) 주간의 자동 등록과 미회신 기관 리마인드.
-- auto_created 는 6개월 주기 예약 작업이 스스로 등록한 주간인지다(결제원 담당자가 등록하면 거짓).
ALTER TABLE update_campaign ADD COLUMN auto_created BOOLEAN DEFAULT FALSE NOT NULL;

-- 진행 중 주간에 "현행화 완료" 를 누르지 않은 기관에 보낸 리마인드 메일 한 번(기관 하나 단위).
-- manual 이 참이면 결제원 담당자가 화면에서 보낸 것(sender_name 이 그 사람), 거짓이면 예약 작업이 보낸 것이다.
-- recipient_count 는 그때 메일을 받은 사람 수(그 기관·업무의 사용 중 계정과 담당자 연락처 이메일, 중복 없이)다.
CREATE TABLE update_campaign_reminder (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      BIGINT        NOT NULL,
    organization_id  BIGINT        NOT NULL,
    sent_at          TIMESTAMP     NOT NULL,
    manual           BOOLEAN       NOT NULL,
    sender_name      VARCHAR(100),
    recipient_count  INTEGER       NOT NULL,
    created_at       TIMESTAMP     NOT NULL,
    created_by       VARCHAR(100)  NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    updated_by       VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_update_campaign_reminder_campaign FOREIGN KEY (campaign_id) REFERENCES update_campaign (id) ON DELETE CASCADE,
    CONSTRAINT fk_update_campaign_reminder_organization FOREIGN KEY (organization_id) REFERENCES organization (id)
);

CREATE INDEX ix_update_campaign_reminder_campaign ON update_campaign_reminder (campaign_id, organization_id);
