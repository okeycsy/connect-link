-- 알림 센터와 발송함. 받는 사람은 회사 이메일로 식별한다(계정 테이블이 생겨도 같은 키를 쓴다).
CREATE TABLE notification (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_email  VARCHAR(200)  NOT NULL,
    type             VARCHAR(40)   NOT NULL,
    business         VARCHAR(30),
    title            VARCHAR(200)  NOT NULL,
    body             VARCHAR(1000),
    link             VARCHAR(300),
    read_at          TIMESTAMP,
    created_at       TIMESTAMP     NOT NULL,
    created_by       VARCHAR(100)  NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    updated_by       VARCHAR(100)  NOT NULL,
    CONSTRAINT ck_notification_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS'))
);

CREATE INDEX ix_notification_recipient ON notification (recipient_email, read_at);

-- 메일·매터모스트 발송 기록. 프로토타입은 PENDING 으로만 남기고 실제로 보내지 않는다.
CREATE TABLE notification_outbox (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id  BIGINT,
    channel          VARCHAR(20)   NOT NULL,
    recipient        VARCHAR(300)  NOT NULL,
    subject          VARCHAR(200),
    body             VARCHAR(2000),
    status           VARCHAR(20)   NOT NULL,
    sent_at          TIMESTAMP,
    created_at       TIMESTAMP     NOT NULL,
    created_by       VARCHAR(100)  NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    updated_by       VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_notification_outbox_notification FOREIGN KEY (notification_id) REFERENCES notification (id),
    CONSTRAINT ck_notification_outbox_channel CHECK (channel IN ('EMAIL', 'MATTERMOST')),
    CONSTRAINT ck_notification_outbox_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);
