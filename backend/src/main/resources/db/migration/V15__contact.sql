-- 가. 참가기관 담당자 연락처. 기관 하나의 업무 하나에 대한 담당자 한 명이 한 행이다(같은 사람이 두 업무를 맡으면 두 행).
-- 계정이 없는 담당자(후임자 등)도 있으므로 계정을 참조하지 않고, 본인 여부는 회사 이메일(소문자)로 맞춘다.
-- last_confirmed_at 은 최근 확인일이다. 고치거나 "변동 없음" 으로 확인할 때 갱신하고, 6개월이 지나면 확인 알림을 띄운다.
-- reconfirm_notified_at 은 6개월 미확인 알림을 보낸 때다. 확인일 뒤에 보냈으면 다시 보내지 않는다.
CREATE TABLE contact (
    id                       BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id          BIGINT        NOT NULL,
    business                 VARCHAR(30)   NOT NULL,
    sub_business             VARCHAR(200),
    name                     VARCHAR(50)   NOT NULL,
    department               VARCHAR(100)  NOT NULL,
    team                     VARCHAR(100),
    job_title                VARCHAR(50),
    job_role                 VARCHAR(20)   NOT NULL,
    contact_rank             VARCHAR(20)   NOT NULL,
    extension_phone          VARCHAR(30)   NOT NULL,
    mobile_phone             VARCHAR(30),
    email                    VARCHAR(200)  NOT NULL,
    last_confirmed_at        TIMESTAMP     NOT NULL,
    last_confirmed_by_name   VARCHAR(100)  NOT NULL,
    reconfirm_notified_at    TIMESTAMP,
    created_at               TIMESTAMP     NOT NULL,
    created_by               VARCHAR(100)  NOT NULL,
    updated_at               TIMESTAMP     NOT NULL,
    updated_by               VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_contact_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT uk_contact_email UNIQUE (organization_id, business, email),
    CONSTRAINT ck_contact_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS')),
    CONSTRAINT ck_contact_job_role CHECK (job_role IN ('BUSINESS', 'IT')),
    CONSTRAINT ck_contact_rank CHECK (contact_rank IN ('PRIMARY', 'SECONDARY'))
);

CREATE INDEX ix_contact_business_organization ON contact (business, organization_id);
CREATE INDEX ix_contact_email ON contact (email);
CREATE INDEX ix_contact_last_confirmed ON contact (last_confirmed_at);

-- 담당자의 전산 세부 직무(복수). 직무가 전산일 때만 있다.
CREATE TABLE contact_it_role (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id  BIGINT        NOT NULL,
    it_role     VARCHAR(30)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL,
    created_by  VARCHAR(100)  NOT NULL,
    updated_at  TIMESTAMP     NOT NULL,
    updated_by  VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_contact_it_role_contact FOREIGN KEY (contact_id) REFERENCES contact (id) ON DELETE CASCADE,
    CONSTRAINT uk_contact_it_role UNIQUE (contact_id, it_role),
    CONSTRAINT ck_contact_it_role CHECK (it_role IN ('DEV', 'OPS', 'INFRA', 'EXTERNAL_LINK', 'CONTROL_ROOM'))
);

-- 정기 변경(현행화) 주간. 결제원 담당자가 업무마다 기간을 등록한다. 같은 업무의 주간은 기간이 겹치지 않는다.
-- 예정·진행 중·종료는 저장하지 않고 오늘 날짜로 정한다.
CREATE TABLE update_campaign (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business         VARCHAR(30)   NOT NULL,
    title            VARCHAR(100)  NOT NULL,
    start_date       DATE          NOT NULL,
    end_date         DATE          NOT NULL,
    registrant_name  VARCHAR(100)  NOT NULL,
    created_at       TIMESTAMP     NOT NULL,
    created_by       VARCHAR(100)  NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    updated_by       VARCHAR(100)  NOT NULL,
    CONSTRAINT ck_update_campaign_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS')),
    CONSTRAINT ck_update_campaign_period CHECK (end_date >= start_date)
);

CREATE INDEX ix_update_campaign_business ON update_campaign (business, start_date);

-- 정기 변경 주간의 기관별 현행화. 기관이 "현행화 완료" 를 누르면 completed_at, 주간 중 담당자 정보가 바뀌면 changed_at 이 찬다.
-- 대상 기관은 그 업무에 참여하는 사용 중 참가기관이고, 아무 일도 없던 기관은 행이 없다(미완료).
CREATE TABLE update_campaign_organization (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id        BIGINT        NOT NULL,
    organization_id    BIGINT        NOT NULL,
    completed_at       TIMESTAMP,
    completed_by_name  VARCHAR(100),
    changed_at         TIMESTAMP,
    created_at         TIMESTAMP     NOT NULL,
    created_by         VARCHAR(100)  NOT NULL,
    updated_at         TIMESTAMP     NOT NULL,
    updated_by         VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_update_campaign_organization_campaign FOREIGN KEY (campaign_id) REFERENCES update_campaign (id) ON DELETE CASCADE,
    CONSTRAINT fk_update_campaign_organization_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT uk_update_campaign_organization UNIQUE (campaign_id, organization_id)
);
