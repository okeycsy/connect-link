-- 일시중단의 대상 업무를 레일 업무와 따로 두는 기준정보(target_work, 금융결제원 업무명 중심, 수십 개)에서 여러 개 고른다(SHY, 2026-10-23).
-- 대상 업무마다 관련 레일 업무(target_work_business, 없을 수 있음)를 두고, 일시중단을 저장할 때 고른 대상 업무의 관련 레일을 모아
-- suspension_business 에 남긴다. 목록·알림·확인 범위는 이 레일로 정한다. 담당자 연락처도 여러 명을 받는다(sort_order 순).
CREATE TABLE target_work (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)  NOT NULL,
    category        VARCHAR(50),
    sort_order      INT           NOT NULL,
    active          BOOLEAN       NOT NULL,
    created_at      TIMESTAMP     NOT NULL,
    created_by      VARCHAR(100)  NOT NULL,
    updated_at      TIMESTAMP     NOT NULL,
    updated_by      VARCHAR(100)  NOT NULL,
    CONSTRAINT uk_target_work_name UNIQUE (name)
);

CREATE TABLE target_work_business (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_work_id  BIGINT        NOT NULL,
    business        VARCHAR(30)   NOT NULL,
    created_at      TIMESTAMP     NOT NULL,
    created_by      VARCHAR(100)  NOT NULL,
    updated_at      TIMESTAMP     NOT NULL,
    updated_by      VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_target_work_business_work FOREIGN KEY (target_work_id) REFERENCES target_work (id),
    CONSTRAINT uk_target_work_business UNIQUE (target_work_id, business),
    CONSTRAINT ck_target_work_business_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS'))
);

-- 레일 업무 이름과 같은 대상 업무 네 개. 이미 있는 일시중단을 이어 붙이는 데 쓴다. 나머지 대상 업무는 관리 화면에서 더한다.
INSERT INTO target_work (name, category, sort_order, active, created_at, created_by, updated_at, updated_by) VALUES
