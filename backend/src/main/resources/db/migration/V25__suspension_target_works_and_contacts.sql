INSERT INTO target_work_business (target_work_id, business, created_at, created_by, updated_at, updated_by)
SELECT w.id, m.business, CURRENT_TIMESTAMP, 'system', CURRENT_TIMESTAMP, 'system'
FROM (VALUES ('계좌통합관리', 'ACCOUNT_INFO'), ('자동이체통합관리', 'AUTO_TRANSFER'), ('대출이동', 'LOAN_TRANSFER'), ('CMS', 'CMS')) AS m (name, business)
JOIN target_work w ON w.name = m.name;

CREATE TABLE suspension_business (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suspension_id   BIGINT        NOT NULL,
    business        VARCHAR(30)   NOT NULL,
    created_at      TIMESTAMP     NOT NULL,
    created_by      VARCHAR(100)  NOT NULL,
    updated_at      TIMESTAMP     NOT NULL,
    updated_by      VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_suspension_business_suspension FOREIGN KEY (suspension_id) REFERENCES suspension (id),
    CONSTRAINT uk_suspension_business UNIQUE (suspension_id, business),
    CONSTRAINT ck_suspension_business_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS'))
);

CREATE INDEX ix_suspension_business_business ON suspension_business (business, suspension_id);

INSERT INTO suspension_business (suspension_id, business, created_at, created_by, updated_at, updated_by)
SELECT id, business, created_at, created_by, updated_at, updated_by FROM suspension;

-- 일시중단이 고른 대상 업무 하나. 고를 때의 이름을 남긴다(기준정보 이름이 바뀌어도 그대로).
CREATE TABLE suspension_target_work (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suspension_id   BIGINT        NOT NULL,
    target_work_id  BIGINT        NOT NULL,
    name            VARCHAR(100)  NOT NULL,
    created_at      TIMESTAMP     NOT NULL,
    created_by      VARCHAR(100)  NOT NULL,
    updated_at      TIMESTAMP     NOT NULL,
    updated_by      VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_suspension_target_work_suspension FOREIGN KEY (suspension_id) REFERENCES suspension (id),
    CONSTRAINT fk_suspension_target_work_work FOREIGN KEY (target_work_id) REFERENCES target_work (id),
    CONSTRAINT uk_suspension_target_work UNIQUE (suspension_id, target_work_id)
);

INSERT INTO suspension_target_work (suspension_id, target_work_id, name, created_at, created_by, updated_at, updated_by)
SELECT s.id, w.id, w.name, s.created_at, s.created_by, s.updated_at, s.updated_by
FROM suspension s
JOIN target_work_business b ON b.business = s.business
JOIN target_work w ON w.id = b.target_work_id;

CREATE TABLE suspension_contact (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suspension_id   BIGINT        NOT NULL,
    sort_order      INT           NOT NULL,
    name            VARCHAR(50)   NOT NULL,
    phone           VARCHAR(30)   NOT NULL,
    email           VARCHAR(200),
    created_at      TIMESTAMP     NOT NULL,
    created_by      VARCHAR(100)  NOT NULL,
    updated_at      TIMESTAMP     NOT NULL,
    updated_by      VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_suspension_contact_suspension FOREIGN KEY (suspension_id) REFERENCES suspension (id)
);

CREATE INDEX ix_suspension_contact_suspension ON suspension_contact (suspension_id, sort_order);

INSERT INTO suspension_contact (suspension_id, sort_order, name, phone, email, created_at, created_by, updated_at, updated_by)
SELECT id, 0, contact_name, contact_phone, contact_email, created_at, created_by, updated_at, updated_by FROM suspension;

