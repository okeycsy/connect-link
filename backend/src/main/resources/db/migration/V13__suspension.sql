-- 라. 참가기관 일시중단 관리. 기관 담당자나 결제원 담당자가 정해진 양식으로 등록한다.
-- 상태: 검토 대기(PENDING_REVIEW) → 검토 중(IN_REVIEW, 결제원 담당자 한 명이라도 확인 시작) → 확정(CONFIRMED, 조치·인수인계 작성) → 완료(COMPLETED, 종료 시각이 지난 확정 건).
-- 등록한 사람은 그때의 이메일·이름으로 남기고, 결제원 담당자가 등록했는지(registrant_kftc)를 따로 둔다.
CREATE TABLE suspension (
    id                   BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business             VARCHAR(30)    NOT NULL,
    sub_business         VARCHAR(200),
    organization_id      BIGINT         NOT NULL,
    start_at             TIMESTAMP      NOT NULL,
    end_at               TIMESTAMP      NOT NULL,
    reason               VARCHAR(2000)  NOT NULL,
    kftc_action          VARCHAR(2000),
    contact_name         VARCHAR(50)    NOT NULL,
    contact_phone        VARCHAR(30)    NOT NULL,
    contact_email        VARCHAR(200),
    extra_note           VARCHAR(2000),
    status               VARCHAR(20)    NOT NULL,
    registrant_email     VARCHAR(200)   NOT NULL,
    registrant_name      VARCHAR(50)    NOT NULL,
    registrant_kftc      BOOLEAN        NOT NULL,
    handover             VARCHAR(2000),
    confirmed_at         TIMESTAMP,
    confirmed_by_email   VARCHAR(200),
    confirmed_by_name    VARCHAR(50),
    completed_at         TIMESTAMP,
    created_at           TIMESTAMP      NOT NULL,
    created_by           VARCHAR(100)   NOT NULL,
    updated_at           TIMESTAMP      NOT NULL,
    updated_by           VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_suspension_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_suspension_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS')),
    CONSTRAINT ck_suspension_status CHECK (status IN ('PENDING_REVIEW', 'IN_REVIEW', 'CONFIRMED', 'COMPLETED')),
    CONSTRAINT ck_suspension_period CHECK (end_at > start_at)
);

CREATE INDEX ix_suspension_business ON suspension (business, start_at);
CREATE INDEX ix_suspension_organization ON suspension (organization_id, start_at);

-- 확인을 시작한 결제원 담당자 한 명. 한 명이라도 있으면 검토 중이다. 기관이 내용을 고치면 지운다(다시 검토 대기).
CREATE TABLE suspension_reviewer (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suspension_id   BIGINT        NOT NULL,
    email           VARCHAR(200)  NOT NULL,
    name            VARCHAR(50)   NOT NULL,
    role_label      VARCHAR(50)   NOT NULL,
    started_at      TIMESTAMP     NOT NULL,
    created_at      TIMESTAMP     NOT NULL,
    created_by      VARCHAR(100)  NOT NULL,
    updated_at      TIMESTAMP     NOT NULL,
    updated_by      VARCHAR(100)  NOT NULL,
    CONSTRAINT fk_suspension_reviewer_suspension FOREIGN KEY (suspension_id) REFERENCES suspension (id),
    CONSTRAINT uk_suspension_reviewer UNIQUE (suspension_id, email)
);

-- 전 영업일 취합 전달 한 번. 보낸 영업일(sent_on)마다 한 번이고, 그 다음 영업일까지 시작하는 확정 건을 모은다.
CREATE TABLE suspension_digest (
    id           BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sent_on      DATE           NOT NULL,
    from_date    DATE           NOT NULL,
    to_date      DATE           NOT NULL,
    item_count   INT            NOT NULL,
    recipients   VARCHAR(500)   NOT NULL,
    body         VARCHAR(8000)  NOT NULL,
    sent_at      TIMESTAMP      NOT NULL,
    created_at   TIMESTAMP      NOT NULL,
    created_by   VARCHAR(100)   NOT NULL,
    updated_at   TIMESTAMP      NOT NULL,
    updated_by   VARCHAR(100)   NOT NULL,
    CONSTRAINT uk_suspension_digest UNIQUE (sent_on)
);
