-- 마. 참가기관 소통 채널(채팅). 업무마다 단체방(BUSINESS) 하나가 있고, 결제원 담당자가 따로 방(CUSTOM)을 만들어 초대한다.
-- 단체방 구성원은 그 업무를 맡은 사용 중 계정이라 저장하지 않고, 따로 초대한 사람만 chat_room_member 에 둔다.
-- 사람은 계정과 같이 회사 이메일(소문자)로 잇고, 보낸·초대한 사람의 이름·기관은 그때 값으로 남긴다.
CREATE TABLE chat_room (
    id                BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business          VARCHAR(30)    NOT NULL,
    type              VARCHAR(20)    NOT NULL,
    name              VARCHAR(50)    NOT NULL,
    created_by_name   VARCHAR(50)    NOT NULL,
    created_at        TIMESTAMP      NOT NULL,
    created_by        VARCHAR(100)   NOT NULL,
    updated_at        TIMESTAMP      NOT NULL,
    updated_by        VARCHAR(100)   NOT NULL,
    CONSTRAINT ck_chat_room_business CHECK (business IN ('ACCOUNT_INFO', 'AUTO_TRANSFER', 'LOAN_TRANSFER', 'CMS')),
    CONSTRAINT ck_chat_room_type CHECK (type IN ('BUSINESS', 'CUSTOM'))
);

CREATE INDEX ix_chat_room_business ON chat_room (business, type);

-- 방에 초대한 사람. 단체방에서는 업무 밖에서 더 부른 사람(예: 대외계)이다.
CREATE TABLE chat_room_member (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id             BIGINT         NOT NULL,
    email               VARCHAR(200)   NOT NULL,
    name                VARCHAR(50)    NOT NULL,
    organization_code   VARCHAR(20)    NOT NULL,
    organization_name   VARCHAR(100)   NOT NULL,
    organization_type   VARCHAR(30)    NOT NULL,
    invited_by_name     VARCHAR(50)    NOT NULL,
    created_at          TIMESTAMP      NOT NULL,
    created_by          VARCHAR(100)   NOT NULL,
    updated_at          TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_chat_room_member_room FOREIGN KEY (room_id) REFERENCES chat_room (id),
    CONSTRAINT uk_chat_room_member UNIQUE (room_id, email)
);

CREATE INDEX ix_chat_room_member_email ON chat_room_member (email);

-- 메시지 한 건. with_attachments 는 보낼 때 첨부(CHAT_MESSAGE)를 올린다고 한 것, attachments_expired 는 보관 기간(1년)이 지나 첨부를 지운 것이다.
CREATE TABLE chat_message (
    id                         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id                    BIGINT         NOT NULL,
    sender_email               VARCHAR(200)   NOT NULL,
    sender_name                VARCHAR(50)    NOT NULL,
    sender_organization_code   VARCHAR(20)    NOT NULL,
    sender_organization_name   VARCHAR(100)   NOT NULL,
    sender_organization_type   VARCHAR(30)    NOT NULL,
    content                    VARCHAR(2000)  NOT NULL,
    with_attachments           BOOLEAN        NOT NULL,
    attachments_expired        BOOLEAN        NOT NULL,
    created_at                 TIMESTAMP      NOT NULL,
    created_by                 VARCHAR(100)   NOT NULL,
    updated_at                 TIMESTAMP      NOT NULL,
    updated_by                 VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_chat_message_room FOREIGN KEY (room_id) REFERENCES chat_room (id)
);

CREATE INDEX ix_chat_message_room ON chat_message (room_id, id);

-- 메시지의 기관 멘션. 결제원은 기관 코드 KFTC 다.
CREATE TABLE chat_message_mention (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id          BIGINT         NOT NULL,
    organization_code   VARCHAR(20)    NOT NULL,
    created_at          TIMESTAMP      NOT NULL,
    created_by          VARCHAR(100)   NOT NULL,
    updated_at          TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_chat_message_mention_message FOREIGN KEY (message_id) REFERENCES chat_message (id),
    CONSTRAINT uk_chat_message_mention UNIQUE (message_id, organization_code)
);

-- "확인" 공감. 답장 대신 확인했다고 남긴다. 한 사람이 한 번이다.
CREATE TABLE chat_message_ack (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id          BIGINT         NOT NULL,
    email               VARCHAR(200)   NOT NULL,
    name                VARCHAR(50)    NOT NULL,
    organization_code   VARCHAR(20)    NOT NULL,
    organization_name   VARCHAR(100)   NOT NULL,
    created_at          TIMESTAMP      NOT NULL,
    created_by          VARCHAR(100)   NOT NULL,
    updated_at          TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_chat_message_ack_message FOREIGN KEY (message_id) REFERENCES chat_message (id),
    CONSTRAINT uk_chat_message_ack UNIQUE (message_id, email)
);

-- 방마다 사람마다 어디까지 읽었는지. 읽지 않은 사람 수와 읽지 않은 메시지 수를 여기서 센다.
CREATE TABLE chat_read_mark (
    id                     BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id                BIGINT         NOT NULL,
    email                  VARCHAR(200)   NOT NULL,
    last_read_message_id   BIGINT         NOT NULL,
    created_at             TIMESTAMP      NOT NULL,
    created_by             VARCHAR(100)   NOT NULL,
    updated_at             TIMESTAMP      NOT NULL,
    updated_by             VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_chat_read_mark_room FOREIGN KEY (room_id) REFERENCES chat_room (id),
    CONSTRAINT uk_chat_read_mark UNIQUE (room_id, email)
);
