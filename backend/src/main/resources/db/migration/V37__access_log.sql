-- 개인정보 처리 접속기록(개인정보의 안전성 확보조치 기준 제8조): 계정, 접속 일시, 접속지 IP, 처리한 정보주체(대상), 수행 업무.
CREATE TABLE access_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accessed_at TIMESTAMP NOT NULL,
    account_email VARCHAR(200) NOT NULL,
    account_name VARCHAR(50),
    organization_name VARCHAR(100),
    ip_address VARCHAR(64) NOT NULL,
    action VARCHAR(100) NOT NULL,
    target VARCHAR(500),
    http_method VARCHAR(10) NOT NULL,
    request_path VARCHAR(500) NOT NULL,
    status_code INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    updated_by VARCHAR(100) NOT NULL
);
CREATE INDEX idx_access_log_accessed_at ON access_log (accessed_at);
CREATE INDEX idx_access_log_account_email ON access_log (account_email);
