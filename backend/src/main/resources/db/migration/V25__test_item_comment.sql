-- 다. 기관 테스트: 결제원 의견에 이어 다는 답글. 기관 결과 한 칸(test_item_result)마다 결제원 담당자와 그 기관 담당자가 시간순으로 이어서 쓴다(한 줄로 이어지는 대화, 답글의 답글을 따로 들이지 않는다).
-- 쓴 사람은 그때의 이메일·이름·직급과 결제원 쪽인지(author_kftc)를 남긴다(결제원 의견처럼 비정규화, 탈퇴해도 그대로). 기관 쪽 소속은 결과 행의 대상 기관이다.
CREATE TABLE test_item_comment (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_item_result_id BIGINT         NOT NULL,
    body                VARCHAR(2000)  NOT NULL,
    author_kftc         BOOLEAN        NOT NULL,
    author_email        VARCHAR(200)   NOT NULL,
    author_name         VARCHAR(50)    NOT NULL,
    author_job_title    VARCHAR(50),
    written_at          TIMESTAMP      NOT NULL,
    created_at          TIMESTAMP      NOT NULL,
    created_by          VARCHAR(100)   NOT NULL,
    updated_at          TIMESTAMP      NOT NULL,
    updated_by          VARCHAR(100)   NOT NULL,
    CONSTRAINT fk_test_item_comment_result FOREIGN KEY (test_item_result_id) REFERENCES test_item_result (id)
);

CREATE INDEX ix_test_item_comment_result ON test_item_comment (test_item_result_id, written_at);
